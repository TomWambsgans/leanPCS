//! The Keccak VM's π1-rec3 graph as Lean data (`formal/RecGraphKeccak`).
//!
//! - `keccak_graph_lean_is_current`: the checked-in `formal/RecGraphKeccak/RecGraphKeccak/Emitted.lean` is what
//!   [`render`] writes for the Keccak VM's π1-rec3 recorded verifier now (`record_verifier(&REFERENCE, KECCAK_REC3,
//!   Claims::Point)`: π1-rec3's Fiat–Shamir shape at the 128-signature reference workload); `UPDATE_LEAN=1` rewrites
//!   it.
//! - `keccak_128_shape`: `leanvm_rec::REFERENCE` is the 128-signature workload's shape
//!   (`leanvm_statement::shapes::reference()`: `⌈log₂ cells⌉`, `2^18`), which the Lean side's `Pi1.keccak128` pins.
//!
//! Self-contained: the renderer is here (the format of `RecGraph.Node`'s `Node`, `Word` and `Graph`), on
//! `leanvm_univariate::contract::{record_verifier, calls, Recorded}` and `leanvm_statement::evm::{record::Node,
//! codegen::Word}` only.
//!
//! `cargo test --release -p leanvm_rec --test lean_graph_keccak`

use std::fmt::Write;

use leanvm_rec::REFERENCE;
use leanvm_statement::evm::codegen::Word;
use leanvm_statement::evm::record::Node;
use leanvm_statement::shapes::{PROGRAM_IV, reference};
use leanvm_univariate::contract::{Recorded, calls, record_verifier};
use leanvm_univariate::{Claims, KECCAK_REC3};

/// The memory cells of the 128-signature run, whose `⌈log₂⌉` is `REFERENCE.log_memory` (`Pi1.keccak128` on the Lean
/// side is `UniKeccak.keccakShapeOf 721598 [..]`).
const KECCAK_128_CELLS: usize = 721_598;

/// The nodes of one Lean definition: the file's definitions stay small enough to elaborate quickly.
const CHUNK: usize = 1000;

fn deep<R: Send + 'static>(f: impl FnOnce() -> R + Send + 'static) -> R {
    std::thread::Builder::new()
        .stack_size(1 << 30)
        .spawn(f)
        .expect("a thread")
        .join()
        .expect("no panic")
}

fn graph_path() -> std::path::PathBuf {
    std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../formal/RecGraphKeccak/RecGraphKeccak/Emitted.lean")
}

/// The Keccak VM's π1-rec3, recorded.
fn recorded() -> Recorded {
    record_verifier(&REFERENCE, KECCAK_REC3, Claims::Point)
}

fn word_nat(bytes: &[u8; 32]) -> String {
    let digits: String = bytes.iter().map(|b| format!("{b:02x}")).collect();
    let trimmed = digits.trim_start_matches('0');
    format!("0x{}", if trimmed.is_empty() { "0" } else { trimmed })
}

fn list<T>(items: impl IntoIterator<Item = T>, show: impl Fn(T) -> String) -> String {
    let items: Vec<String> = items.into_iter().map(show).collect();
    format!("[{}]", items.join(", "))
}

fn node_text(node: &Node) -> String {
    match *node {
        Node::Const([c0, c1, c2]) => format!("const 0x{c0:x} 0x{c1:x} 0x{c2:x}"),
        Node::Statement(k) => format!("statement {k}"),
        Node::Frame(..) => unreachable!("π1's graph reads no frame"),
        Node::Input { offset, len } => format!("input {offset} {len}"),
        Node::Add(a, b) => format!("add {a} {b}"),
        Node::Mul(a, b) => format!("mul {a} {b}"),
        Node::Seed => "seed".to_string(),
        Node::Hash(state, from, to) => format!("hash {state} {from} {to}"),
        Node::Low(h) => format!("low {h}"),
        Node::Narrow(h) => format!("narrow {h}"),
        // π1-rec4's; the Lean states π1-rec3, which has none.
        Node::Wide(h, k) => format!("wide {h} {k}"),
        Node::Bits(v, shift, width) => format!("bits {v} {shift} {width}"),
        Node::RingWeight(kernel, n) => format!("ringWeight {kernel} {n}"),
    }
}

fn word_text(word: &Word) -> String {
    match word {
        Word::Node(id) => format!("Word.node {id}"),
        Word::Const(bytes) => format!("Word.const {}", word_nat(bytes)),
        Word::Stream(at) => format!("Word.stream {at}"),
        Word::Stored(_) => panic!("π1's contract stores nothing: the setup roots are code constants"),
    }
}

/// The Lean file: the graph's nodes in creation order, its checks, its ring-weight kernels, the words of its
/// claims (which the contract checks declared), the stream's length and where it holds `C1`'s and `C2`'s roots.
fn render(recorded: &Recorded) -> String {
    let graph = &recorded.graph;
    let call_words = calls(recorded);
    let hashes = graph.nodes.iter().filter(|n| matches!(n, Node::Hash(..))).count();
    let ops = graph
        .nodes
        .iter()
        .filter(|n| matches!(n, Node::Add(..) | Node::Mul(..)))
        .count();
    let mut out = String::new();
    let w = &mut out;
    writeln!(w, "-- Part of this repository. MIT OR Apache-2.0; see AGENTS.md.").unwrap();
    writeln!(w, "-- Generated by `crates/leanvm/rec/tests/lean_graph_keccak.rs` (`render`) from the Keccak VM's π1-rec3").unwrap();
    writeln!(w, "-- recorded verifier. Do not edit: `UPDATE_LEAN=1 cargo test --release -p leanvm_rec --test lean_graph_keccak`").unwrap();
    writeln!(w, "-- rewrites it, and the test fails while it is stale.").unwrap();
    writeln!(w, "import RecGraph.Node").unwrap();
    writeln!(w).unwrap();
    writeln!(w, "/-!").unwrap();
    writeln!(w, "# The Keccak VM's π1-rec3 recorded graph").unwrap();
    writeln!(w).unwrap();
    writeln!(w, "`leanvm_univariate::contract::record_verifier` at the Keccak VM's 128-signature shape (`leanvm_rec::REFERENCE`), with").unwrap();
    writeln!(
        w,
        "`KECCAK_REC3` (`FsShape::Rec3`, a skip of 3) and `Claims::Point`: {} nodes ({ops} additions",
        graph.nodes.len()
    )
    .unwrap();
    writeln!(
        w,
        "and products of `E`, {hashes} Keccak-256 calls), {} values required zero and {} nonzero, {} ring-weight kernels, {} claims",
        graph.zero.len(),
        graph.nonzero.len(),
        graph.kernels.len(),
        call_words.len()
    )
    .unwrap();
    writeln!(
        w,
        "calls of {} words, a stream of {} bytes.",
        list(call_words.iter().map(|c| c.words().len()), |n| n.to_string()),
        recorded.stream_len
    )
    .unwrap();
    writeln!(w).unwrap();
    writeln!(w, "Data only: nothing here is evaluated by the kernel; `RecGraph.Semantics` gives it its meaning, and the differential").unwrap();
    writeln!(w, "check (`RecGraphKeccakTest/Pi1Check.lean`) reads it with `lake env lean`.").unwrap();
    writeln!(w, "-/").unwrap();
    writeln!(w).unwrap();
    writeln!(w, "namespace RecGraphKeccak.Emitted").unwrap();
    writeln!(w).unwrap();
    writeln!(w, "open RecGraph Node").unwrap();
    writeln!(w).unwrap();
    let chunks: Vec<&[Node]> = graph.nodes.chunks(CHUNK).collect();
    for (c, chunk) in chunks.iter().enumerate() {
        writeln!(w, "/-- Nodes {} to {}, in the order recorded. -/", c * CHUNK, c * CHUNK + chunk.len() - 1).unwrap();
        writeln!(w, "def nodes{c} : List Node := [").unwrap();
        for (i, node) in chunk.iter().enumerate() {
            let comma = if i + 1 < chunk.len() { "," } else { "" };
            writeln!(w, "  {}{comma}", node_text(node)).unwrap();
        }
        writeln!(w, "]").unwrap();
        writeln!(w).unwrap();
    }
    writeln!(w, "/-- The nodes, in the order recorded: node `i` reads only nodes below `i`. -/").unwrap();
    let parts: Vec<String> = (0..chunks.len()).map(|c| format!("nodes{c}")).collect();
    writeln!(w, "def nodes : Array Node := ({}).toArray", parts.join(" ++ ")).unwrap();
    writeln!(w).unwrap();
    writeln!(w, "/-- The values the verifier requires zero, in the order required. -/").unwrap();
    writeln!(w, "def zero : List Nat := {}", list(graph.zero.iter(), |(id, _)| id.to_string())).unwrap();
    writeln!(w).unwrap();
    writeln!(w, "/-- The values the verifier requires nonzero, in the order required. -/").unwrap();
    writeln!(w, "def nonzero : List Nat := {}", list(graph.nonzero.iter(), |(id, _)| id.to_string())).unwrap();
    writeln!(w).unwrap();
    writeln!(
        w,
        "/-- Each ring-weight kernel's operands: the point, `1 + r`, the map (`Node.ringWeight k n`: `n` coordinates). -/"
    )
    .unwrap();
    writeln!(w, "def kernels : Array (List Nat) := #[").unwrap();
    for (k, kernel) in graph.kernels.iter().enumerate() {
        let comma = if k + 1 < graph.kernels.len() { "," } else { "" };
        writeln!(w, "  {}{comma}", list(kernel.iter(), |x| x.to_string())).unwrap();
    }
    writeln!(w, "]").unwrap();
    writeln!(w).unwrap();
    for (c, claim) in call_words.iter().enumerate() {
        let call = claim.words();
        writeln!(w, "/-- The words of claim {c}: its root, its out-of-domain answer, its point, its value. -/").unwrap();
        writeln!(w, "def call{c} : List Word := [").unwrap();
        for (i, word) in call.iter().enumerate() {
            let comma = if i + 1 < call.len() { "," } else { "" };
            writeln!(w, "  {}{comma}", word_text(word)).unwrap();
        }
        writeln!(w, "]").unwrap();
        writeln!(w).unwrap();
    }
    let call_names: Vec<String> = (0..call_words.len()).map(|c| format!("call{c}")).collect();
    writeln!(w, "/-- The claims' words, in order: `C1`, `C2`, the setup. -/").unwrap();
    writeln!(w, "def calls : List (List Word) := [{}]", call_names.join(", ")).unwrap();
    writeln!(w).unwrap();
    writeln!(w, "/-- The stream's bytes (calldata after the selector and the public input). -/").unwrap();
    writeln!(w, "def streamLen : Nat := {}", recorded.stream_len).unwrap();
    writeln!(w).unwrap();
    writeln!(w, "/-- Where the stream holds `C1`'s and `C2`'s roots. -/").unwrap();
    writeln!(w, "def rootsAt : List Nat := {}", list(recorded.roots_at.iter(), |x| x.to_string())).unwrap();
    writeln!(w).unwrap();
    writeln!(w, "/-- **The Keccak VM's π1-rec3 graph.** -/").unwrap();
    writeln!(w, "def graph : Graph where").unwrap();
    for field in ["nodes", "zero", "nonzero", "kernels", "calls", "streamLen"] {
        writeln!(w, "  {field} := {field}").unwrap();
    }
    writeln!(w).unwrap();
    writeln!(w, "end RecGraphKeccak.Emitted").unwrap();
    out
}

/// `REFERENCE` is the 128-signature workload (`leanvm_statement::shapes::reference()`): its rows, and its memory
/// `⌈log₂⌉` of the run's 721,598 cells, which the Lean side's `Pi1.keccak128` pins.
#[test]
fn keccak_128_shape() {
    let w = reference();
    assert_eq!(w.memory_cells, KECCAK_128_CELLS as u64);
    assert_eq!(REFERENCE.table_rows.map(|r| r as u64), w.shape.table_rows.map(|r| r as u64));
    assert_eq!(REFERENCE.log_memory as u64, w.shape.log_memory as u64);
    assert_eq!(REFERENCE.log_memory as u64, 64 - (KECCAK_128_CELLS as u64 - 1).leading_zeros() as u64);
    assert_eq!(REFERENCE.log_bytecode, 18);
}

/// The checked-in Lean graph is the Keccak VM's π1-rec3 recorded verifier: `UPDATE_LEAN=1` rewrites it.
#[test]
fn keccak_graph_lean_is_current() {
    let (text, iv) = deep(|| {
        let r = recorded();
        (render(&r), r.iv(&PROGRAM_IV))
    });
    eprintln!(
        "the Keccak graph: {} bytes, {} lines; its contract IV {}",
        text.len(),
        text.lines().count(),
        iv.iter().map(|b| format!("{b:02x}")).collect::<String>()
    );
    let path = graph_path();
    if std::env::var_os("UPDATE_LEAN").is_some() {
        std::fs::create_dir_all(path.parent().expect("a directory")).expect("the directory");
        std::fs::write(&path, &text).expect("the Lean graph written");
        return;
    }
    let current = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        current == text,
        "{} is stale: run `UPDATE_LEAN=1 cargo test --release -p leanvm_rec --test lean_graph_keccak \
         keccak_graph_lean_is_current`",
        path.display()
    );
}
