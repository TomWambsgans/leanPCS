//! The deployed contract's recorded graph as a Lean term (`formal/Implementation/Graph.lean`), and test vectors
//! for the Lean interpreter of that graph (`formal/Implementation`, layer F5 of `formal/README.md`).
//!
//! The graph is what [`crate::quotient::contract`] compiles: `quotient::protocol::reduce` run on the recorder,
//! with the outputs the fields of the PCS claims it checks declared (three; the checked-in `Graph.lean` is still
//! `f96a7938`'s six-claim contract's, which `formal/` proves). [`render`] writes it, with the constants the reduction
//! reads (the Cantor basis, `tau`, `b`, the extension's coordinates), as Lean definitions; the test
//! `graph_lean_is_current` fails when the checked-in file is not what [`render`] writes now (run it with
//! `UPDATE_LEAN=1` to rewrite the file; ignored until the Lean is ported). [`vectors`] writes calldata and what the
//! Rust verifier makes of it, the claims' bytes, for the Lean executable to compare with its interpretation of the graph.

use std::fmt::Write;

use primitives::field::{F64, F192};
use quotient::opening::Commitment;
use quotient::domain::{beta, coordinates, row_vanishing};
use quotient::protocol::{extension, label};
use quotient::statement::Statement;
use quotient::transcript::Proof;

use crate::codegen::{Ending, Word};
use crate::quotient::{CALLDATA_LEN, Recorded, deployed, pcs_claims};
use crate::record::Node;

/// The rows of the deployed circuit.
pub const LOG_ROWS: usize = quotient::circuit::LOG_ROWS;

fn nat(x: F192) -> String {
    let wide = (x.c2 as u128) << 64 | x.c1 as u128;
    if wide == 0 {
        format!("0x{:x}", x.c0)
    } else {
        format!("0x{wide:x}{:016x}", x.c0)
    }
}

fn base(x: F64) -> String {
    format!("0x{:x}", x.0)
}

fn word(bytes: &[u8; 32]) -> String {
    let digits: String = bytes.iter().map(|b| format!("{b:02x}")).collect();
    let trimmed = digits.trim_start_matches('0');
    format!("0x{}", if trimmed.is_empty() { "0" } else { trimmed })
}

fn list<T>(items: impl IntoIterator<Item = T>, show: impl Fn(T) -> String) -> String {
    let items: Vec<String> = items.into_iter().map(show).collect();
    format!("[{}]", items.join(", "))
}

/// The Lean file: the graph's nodes, the values it requires nonzero, the words the contract writes and how the
/// three calls split them, and the constants.
pub fn render() -> String {
    let Recorded {
        graph,
        outputs,
        ending,
        inputs,
    } = deployed(LOG_ROWS);
    let Ending::Declared(claims) = ending else {
        unreachable!("the deployed contract checks declared claims")
    };
    let mut out = String::new();
    let w = &mut out;
    writeln!(w, "-- Part of this repository. MIT OR Apache-2.0; see AGENTS.md.").unwrap();
    writeln!(
        w,
        "-- Generated by `crates/membership/evm/src/lean.rs` (`render`) from the graph `crates/membership/evm/src/quotient.rs` compiles for the"
    )
    .unwrap();
    writeln!(
        w,
        "-- deployed contract (`deployed({LOG_ROWS})`). Do not edit: `UPDATE_LEAN=1 cargo test -p evm graph_lean_is_current`"
    )
    .unwrap();
    writeln!(w, "-- rewrites it, and the test fails while it is stale.").unwrap();
    writeln!(w, "import Implementation.Node").unwrap();
    writeln!(w).unwrap();
    writeln!(w, "/-!").unwrap();
    writeln!(w, "# The deployed contract's graph").unwrap();
    writeln!(w).unwrap();
    writeln!(
        w,
        "`quotient::protocol::reduce` run on `crates/membership/evm/src/record.rs`'s recorder, at `2^{LOG_ROWS}` rows: {} nodes, {} values",
        graph.nodes.len(),
        graph.nonzero.len()
    )
    .unwrap();
    writeln!(
        w,
        "required nonzero, {} output words, {} PCS claims checked declared, {inputs} scalars of the proof read.",
        outputs.len(),
        claims.len()
    )
    .unwrap();
    writeln!(w, "-/").unwrap();
    writeln!(w).unwrap();
    writeln!(w, "namespace Implementation.Emitted").unwrap();
    writeln!(w).unwrap();
    writeln!(w, "open Implementation.Node").unwrap();
    writeln!(w).unwrap();
    writeln!(w, "/-- The rows: `2^logRows`. -/").unwrap();
    writeln!(w, "def logRows : Nat := {LOG_ROWS}").unwrap();
    writeln!(w).unwrap();
    writeln!(w, "/-- The scalars of the proof the graph reads. -/").unwrap();
    writeln!(w, "def inputs : Nat := {inputs}").unwrap();
    writeln!(w).unwrap();
    writeln!(w, "/-- The nodes, in the order recorded: node `i` reads only nodes below `i`. -/").unwrap();
    writeln!(w, "def nodes : List Node := [").unwrap();
    let n = graph.nodes.len();
    for (i, node) in graph.nodes.iter().enumerate() {
        let text = match *node {
            Node::Const([c0, c1, c2]) => format!("const {}", nat(F192::new(c0, c1, c2))),
            Node::Statement(k) => format!("statement {k}"),
            Node::Root(k) => format!("root {k}"),
            Node::Input(i) => format!("input {i}"),
            Node::Add(a, b) => format!("add {a} {b}"),
            Node::Mul(a, b) => format!("mul {a} {b}"),
            Node::Frobenius(a) => format!("frob {a}"),
            Node::Seed => "seed".to_string(),
            Node::Hash(state, scalars, k) => {
                format!("hash {state} {}", list(&scalars[..k as usize], |x| x.to_string()))
            }
            Node::Low(a) => format!("low {a}"),
        };
        let comma = if i + 1 < n { "," } else { "" };
        writeln!(w, "  {text}{comma}").unwrap();
    }
    writeln!(w, "]").unwrap();
    writeln!(w).unwrap();
    writeln!(w, "/-- The values the contract requires nonzero, in the order checked. -/").unwrap();
    writeln!(w, "def nonzero : List Nat := {}", list(&graph.nonzero, |x| x.to_string())).unwrap();
    writeln!(w).unwrap();
    writeln!(
        w,
        "/-- The words the contract writes, each once: the fields of the claims it checks declared. -/"
    )
    .unwrap();
    writeln!(w, "def outputs : List Word := [").unwrap();
    for (i, out) in outputs.iter().enumerate() {
        let text = match out {
            Word::Node(id) => format!("Word.node {id}"),
            Word::Const(bytes) => format!("Word.const {}", word(bytes)),
            Word::Calldata(offset) => format!("Word.calldata {offset}"),
            Word::StoredRoot => "Word.storedRoot".to_string(),
            Word::StoredOod => "Word.storedOod".to_string(),
        };
        let comma = if i + 1 < outputs.len() { "," } else { "" };
        writeln!(w, "  {text}{comma}").unwrap();
    }
    writeln!(w, "]").unwrap();
    writeln!(w).unwrap();
    writeln!(
        w,
        "/-- Each PCS claim, in order: the output words of its root, its out-of-domain answer, its point, its value. -/"
    )
    .unwrap();
    writeln!(
        w,
        "def claims : List (Nat × Nat × List Nat × Nat) := {}",
        list(&claims, |c| format!("({}, {}, {}, {})", c.root, c.ood, list(&c.point, |x| x.to_string()), c.value))
    )
    .unwrap();
    writeln!(w).unwrap();
    let zero = Statement {
        y: [0; 32],
        root: [0; 32],
    };
    writeln!(w, "/-- The transcript's name, the label's first sixteen bytes. -/").unwrap();
    writeln!(
        w,
        "def name : List Nat := {}",
        list(
            &label(
                &Commitment {
                    root: [0; 32],
                    ood: F192::ZERO,
                },
                &zero
            )[..16],
            |b| format!("0x{b:02x}")
        )
    )
    .unwrap();
    writeln!(w).unwrap();
    writeln!(w, "/-- `quotient::domain::beta()`: the Cantor basis of `GF(2^64)`. -/").unwrap();
    writeln!(w, "def beta : List Nat := {}", list(beta().iter(), |&x| base(x))).unwrap();
    writeln!(w).unwrap();
    let m = LOG_ROWS + 2;
    writeln!(w, "/-- `quotient::domain::row_vanishing({m})`. -/").unwrap();
    writeln!(w, "def tau : List Nat := {}", list(row_vanishing(m), base)).unwrap();
    writeln!(w).unwrap();
    writeln!(w, "/-- `quotient::domain::coordinates(11)`. -/").unwrap();
    writeln!(w, "def coords : List Nat := {}", list(coordinates(11), base)).unwrap();
    writeln!(w).unwrap();
    let ([y0, y1], scale) = extension();
    writeln!(
        w,
        "/-- `quotient::protocol::extension()`: `Y / (1 + Y)`, `Y^2 / (1 + Y^2)`, `1 / ((1 + Y) (1 + Y^2))`. -/"
    )
    .unwrap();
    writeln!(w, "def y0 : Nat := {}", nat(y0)).unwrap();
    writeln!(w, "def y1 : Nat := {}", nat(y1)).unwrap();
    writeln!(w, "def scale : Nat := {}", nat(scale)).unwrap();
    writeln!(w).unwrap();
    writeln!(w, "end Implementation.Emitted").unwrap();
    out
}

/// A proof and statement read back from calldata of the verifier ([`crate::quotient::calldata`]'s inverse, without
/// its last byte, the frame's index).
fn parse(calldata: &[u8]) -> (Statement, Proof) {
    assert_eq!(calldata.len(), CALLDATA_LEN - 1);
    let be = |at: usize| u64::from_be_bytes(calldata[at..at + 8].try_into().unwrap());
    let statement = Statement {
        y: calldata[..32].try_into().unwrap(),
        root: calldata[32..64].try_into().unwrap(),
    };
    let scalar = |i: usize| {
        let at = 128 + 24 * i;
        F192::new(be(at + 16), be(at + 8), be(at))
    };
    let mut stream = Vec::new();
    for k in 0..2 {
        let root: [u8; 32] = calldata[64 + 32 * k..96 + 32 * k].try_into().unwrap();
        stream.extend(quotient::transcript::root_halves(&root));
        stream.push(scalar(k));
    }
    stream.extend((2..crate::quotient::INPUTS).map(scalar));
    (statement, Proof { stream })
}

/// The claims the deployed contract checks declared for `calldata` (without its frame byte), by the Rust verifier:
/// the three claims' bytes back to back, or `None` where the verifier rejects.
pub fn expected(index: &Commitment, calldata: &[u8]) -> Option<Vec<u8>> {
    let (statement, proof) = parse(calldata);
    let (commitments, claims) = quotient::protocol::verify(index, &statement, &proof, LOG_ROWS).ok()?;
    Some(pcs_claims(index, &commitments, &claims).iter().flat_map(|claim| claim.encode()).collect())
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

/// Random calldata of the verifier (without its frame byte), its roots' words arbitrary.
fn random_calldata(rng: &mut primitives::test_rng::Rng) -> Vec<u8> {
    (0..CALLDATA_LEN - 1).map(|_| rng.next_u8()).collect()
}

fn random_index(rng: &mut primitives::test_rng::Rng) -> Commitment {
    Commitment {
        root: std::array::from_fn(|_| rng.next_u8()),
        ood: F192::new(rng.next_u64(), rng.next_u64(), rng.next_u64()),
    }
}

/// `count` lines of test vectors: an index commitment (its root, its out-of-domain answer as 24 bytes), calldata of
/// the verifier (without its frame byte), and the claims the Rust verifier has the contract check declared (or
/// `reject`), each in hex, separated by spaces.
pub fn vectors(seed: u64, count: usize) -> String {
    let mut rng = primitives::test_rng::Rng::new(seed);
    let mut out = String::new();
    for _ in 0..count {
        let index = random_index(&mut rng);
        let calldata = random_calldata(&mut rng);
        let expected = expected(&index, &calldata).map_or("reject".to_string(), |words| hex(&words));
        let ood = pcs_claim::element_bytes(index.ood);
        writeln!(out, "{} {} {} {expected}", hex(&index.root), hex(&ood), hex(&calldata)).unwrap();
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::machine::{Chain, PcsFrame};
    use crate::quotient::{PCS_FRAME, calldata, contract, init_code};
    use revm::primitives::Address;

    fn graph_path() -> std::path::PathBuf {
        std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../formal/Implementation/Graph.lean")
    }

    /// The checked-in Lean graph is the deployed contract's: `UPDATE_LEAN=1` rewrites it. The contract is that of
    /// `docs/membership/PERF_GAS2.md` (three claims, no selector) and `formal/` still the six claims': the graph is
    /// stale until the Lean is ported, so the check is ignored here.
    #[test]
    #[ignore = "formal/Implementation/Graph.lean is the six-claim contract's until the Lean is ported (PERF_GAS.md)"]
    fn graph_lean_is_current() {
        let rendered = render();
        let path = graph_path();
        if std::env::var_os("UPDATE_LEAN").is_some() {
            std::fs::write(&path, &rendered).expect("the Lean graph written");
            return;
        }
        let current = std::fs::read_to_string(&path).unwrap_or_default();
        assert!(
            current == rendered,
            "{} is stale: run `UPDATE_LEAN=1 cargo test -p evm graph_lean_is_current`",
            path.display()
        );
    }

    /// The vectors' expected words are the claims the contract checks: the contract succeeds against a frame
    /// holding exactly those openings.
    #[test]
    fn vectors_are_the_contracts_calls() {
        let mut rng = primitives::test_rng::Rng::new(0x1ea4);
        let index = random_index(&mut rng);
        let mut chain = Chain::default();
        let address = chain
            .deploy(&init_code(&contract(LOG_ROWS), &index, Address::with_last_byte(0x0e)))
            .0
            .expect("a deployment");
        for _ in 0..8 {
            let data = random_calldata(&mut rng);
            let (statement, proof) = parse(&data);
            assert_eq!(calldata(&statement, &proof).unwrap(), [&data[..], &[PCS_FRAME]].concat(), "parse inverts calldata");
            let words = expected(&index, &data).expect("random calldata reduces");
            let (commitments, claims) =
                quotient::protocol::verify(&index, &statement, &proof, LOG_ROWS).expect("a reduction");
            let mut block = PcsFrame::default();
            let mut joined = Vec::new();
            for claim in pcs_claims(&index, &commitments, &claims) {
                block.declare(&claim);
                joined.extend(claim.encode());
            }
            assert_eq!(words, joined);
            let outcome = chain.call(address, &[&data[..], &[PCS_FRAME]].concat(), &block);
            assert!(outcome.output.is_some());
            assert_eq!(outcome.claims.concat(), words, "the contract checks the vector's words");
        }
    }

    /// `LEAN_VECTORS=path cargo test -p evm write_lean_vectors -- --ignored` writes `LEAN_VECTOR_COUNT` (default
    /// 1000) vectors for `formal/Implementation`'s differential test.
    #[test]
    #[ignore]
    fn write_lean_vectors() {
        let Ok(path) = std::env::var("LEAN_VECTORS") else {
            eprintln!("LEAN_VECTORS unset: nothing written");
            return;
        };
        let count = std::env::var("LEAN_VECTOR_COUNT").map_or(1000, |n| n.parse().expect("a count"));
        let seed = std::env::var("LEAN_VECTOR_SEED").map_or(0x5eed, |n| n.parse().expect("a seed"));
        std::fs::write(path, vectors(seed, count)).expect("the vectors written");
    }
}
